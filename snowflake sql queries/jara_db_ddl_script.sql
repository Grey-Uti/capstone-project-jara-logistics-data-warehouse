--========================================
-- DDL to create the database (JARA_DB) and SCHEMA (Raw)
--=========================================
CREATE DATABASE IF NOT EXISTS JARA_DB;
USE DATABASE JARA_DB;
CREATE SCHEMA IF NOT EXISTS RAW;


-- Permission grant for DBT Objects --

USE ROLE ACCOUNTADMIN;

GRANT USAGE  ON DATABASE JARA_DB TO ROLE PC_DBT_ROLE;
GRANT USAGE  ON SCHEMA   JARA_DB.RAW TO ROLE PC_DBT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA JARA_DB.RAW TO ROLE PC_DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA JARA_DB.RAW TO ROLE PC_DBT_ROLE;